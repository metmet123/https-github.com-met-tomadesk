def slide_list() -> list[tuple[int, dict]]:
    """(섹션 번호, 슬라이드)를 화면에 나오는 순서대로 펼친다."""
    flat: list[tuple[int, dict]] = []
    for index, section in enumerate(MANUAL_SECTIONS):
        for slide in section["slides"]:
            flat.append((index, slide))
    return flat
